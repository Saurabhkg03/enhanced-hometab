var import_obsidian18 = require("obsidian");
var ActivityTracker = class extends import_obsidian18.Component {
  constructor(app, settingsManager) {
    super();
    this.debounceTimer = null;
    this.app = app;
    this.settingsManager = settingsManager;
  }
  onload() {
    this.registerEvent(
      this.app.workspace.on("file-open", (file) => {
        if (file) {
          this.trackFileOpen(file);
        }
      })
    );
    this.registerEvent(
      this.app.vault.on("modify", (file) => {
        if (file instanceof import_obsidian18.TFile) {
          this.trackFileModify(file);
        }
      })
    );
  }
  trackFileOpen(file) {
    if (!this.settingsManager.settings.continueWorkingData) {
      this.settingsManager.settings.continueWorkingData = {};
    }
    const data = this.settingsManager.settings.continueWorkingData;
    const noteRef = {
      path: file.path,
      title: file.basename,
      timestamp: Date.now()
    };
    if (file.extension === "canvas") {
      data.lastCanvas = noteRef;
    } else if (file.extension === "md") {
      data.lastOpenedNote = noteRef;
    }
    this.debouncedSave();
  }
  trackFileModify(file) {
    if (!this.settingsManager.settings.continueWorkingData) {
      this.settingsManager.settings.continueWorkingData = {};
    }
    const data = this.settingsManager.settings.continueWorkingData;
    if (file.extension === "md" || file.extension === "canvas") {
      data.lastEditedNote = {
        path: file.path,
        title: file.basename,
        timestamp: Date.now()
      };
      this.debouncedSave();
    }
  }
  trackWorkspaceSession() {
    if (!this.settingsManager.settings.continueWorkingData) {
      this.settingsManager.settings.continueWorkingData = {};
    }
    const leaves = this.app.workspace.getLeavesOfType("markdown");
    const canvasLeaves = this.app.workspace.getLeavesOfType("canvas");
    const allLeaves = [...leaves, ...canvasLeaves];
    const tabs = allLeaves.map((l) => {
      const file = l.view.file;
      return file ? { path: file.path, title: file.basename, type: file.extension } : null;
    }).filter((t) => t !== null);
    if (tabs.length > 0) {
      this.settingsManager.settings.continueWorkingData.lastWorkspace = {
        timestamp: Date.now(),
        tabsCount: tabs.length,
        tabs
      };
    }
  }
  debouncedSave() {
    if (this.debounceTimer) {
      window.clearTimeout(this.debounceTimer);
    }
    this.debounceTimer = window.setTimeout(async () => {
      this.trackWorkspaceSession();
      await this.settingsManager.saveSettings(true);
    }, 3e3);
  }
};

